-- Application accounts
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'CUSTOMER', 'DRIVER'))
);

-- Connect customer profiles to application accounts
ALTER TABLE customers
    ADD COLUMN IF NOT EXISTS user_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_name = 'fk_customers_user'
          AND table_name = 'customers'
    ) THEN
        ALTER TABLE customers
            ADD CONSTRAINT fk_customers_user
            FOREIGN KEY (user_id) REFERENCES app_users(id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_customers_user_id
    ON customers(user_id);

-- Connect driver profiles to application accounts
ALTER TABLE drivers
    ADD COLUMN IF NOT EXISTS user_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_name = 'fk_drivers_user'
          AND table_name = 'drivers'
    ) THEN
        ALTER TABLE drivers
            ADD CONSTRAINT fk_drivers_user
            FOREIGN KEY (user_id) REFERENCES app_users(id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_drivers_user_id
    ON drivers(user_id);

-- Refresh tokens
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
